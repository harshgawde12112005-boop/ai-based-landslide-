from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime, timezone
from ml_engine import calculate_landslide_risk

app = FastAPI(
    title="LandGuard AI - Landslide Risk Intelligence Platform",
    description="Geotechnical AI & Early Warning Hazard Detection Platform",
    version="2.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class SensorData(BaseModel):
    rainfall_mm: float = Field(..., ge=0, le=500, description="24h cumulative rainfall in mm")
    soil_moisture_pct: float = Field(..., ge=0, le=100, description="Volumetric soil moisture percentage")
    slope_deg: float = Field(..., ge=0, le=90, description="Slope inclination angle in degrees")
    pore_pressure_kpa: Optional[float] = Field(None, ge=0, le=200, description="Pore-water pressure in kPa")
    vegetation_cover_pct: Optional[float] = Field(65.0, ge=0, le=100, description="NDVI vegetation index percentage")
    seismic_pga: Optional[float] = Field(0.05, ge=0, le=1.0, description="Peak Ground Acceleration in g")
    zone_id: Optional[str] = Field("zone-sikkim-1", description="Identifier of the monitored slope sector")


class ExportReportRequest(BaseModel):
    zone_name: str
    risk_pct: int
    risk_level: str
    factor_of_safety: float
    rainfall_mm: float
    soil_moisture_pct: float
    slope_deg: float
    operator_notes: Optional[str] = "Automated sensor telemetry report generated by LandGuard AI."


