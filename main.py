@app.post("/api/predict")
def predict_risk(data: SensorData):
    (
        risk_pct,
        risk_level,
        factor_of_safety,
        contributors,
        confidence,
        ai_summary,
        recommendation,
        chain_reaction,
        metrics,
    ) = calculate_landslide_risk(
        rainfall=data.rainfall_mm,
        soil_moisture=data.soil_moisture_pct,
        slope=data.slope_deg,
        pore_pressure=data.pore_pressure_kpa,
        vegetation_cover=data.vegetation_cover_pct,
        seismic_pga=data.seismic_pga,
    )

    return {
        "overall_risk_pct": risk_pct,
        "risk_level": risk_level,
        "factor_of_safety": factor_of_safety,
        "contributors": contributors,
        "confidence": confidence,
        "ai_summary": ai_summary,
        "recommendation": recommendation,
        "chain_reaction": chain_reaction,
        "metrics": metrics,
        "inputs": {
            "rainfall_mm": data.rainfall_mm,
            "soil_moisture_pct": data.soil_moisture_pct,
            "slope_deg": data.slope_deg,
            "pore_pressure_kpa": metrics.get("pore_pressure_kpa"),
            "vegetation_cover_pct": data.vegetation_cover_pct,
            "seismic_pga": data.seismic_pga,
        },
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }


@app.get("/api/zones")
def get_monitored_zones():
    # Calculate live risk rating for each zone
    enhanced_zones = []
    for zone in MONITORED_ZONES:
        risk_score, risk_level, fos, _, conf, summary, _, chain, _ = calculate_landslide_risk(
            rainfall=zone["rainfall_mm"],
            soil_moisture=zone["soil_moisture_pct"],
            slope=zone["slope_deg"],
        )
        enhanced_zones.append({
            **zone,
            "risk_pct": risk_score,
            "risk_level": risk_level,
            "factor_of_safety": fos,
            "confidence": conf,
            "ai_summary": summary,
            "chain_reaction": chain,
        })
    return {"zones": enhanced_zones, "count": len(enhanced_zones)}


